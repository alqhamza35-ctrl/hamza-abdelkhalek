let currentLang = localStorage.getItem("lang") || "ar";

function getTranslation(key, lang = currentLang) {
    return translations[key]?.[lang] || key;
}

function updatePageMetadata(lang) {
    const page = document.body.dataset.page;
    if (!page) return;

    document.title = getTranslation(`page-${page}-title`, lang);
    const description = document.querySelector('meta[name="description"]');
    if (description) description.content = getTranslation(`page-${page}-description`, lang);
}

function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem("lang", lang);
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        element.textContent = getTranslation(element.dataset.i18n, lang);
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        element.placeholder = getTranslation(element.dataset.i18nPlaceholder, lang);
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
        element.setAttribute("aria-label", getTranslation(element.dataset.i18nAria, lang));
    });

    const languageButton = document.querySelector(".lang-toggle");
    if (languageButton) languageButton.textContent = lang === "ar" ? "EN" : "AR";

    updatePageMetadata(lang);
    document.dispatchEvent(new CustomEvent("languagechange"));
}

function toggleLanguage() {
    changeLanguage(currentLang === "ar" ? "en" : "ar");
}

window.getTranslation = getTranslation;
window.toggleLanguage = toggleLanguage;

document.addEventListener("DOMContentLoaded", () => changeLanguage(currentLang));
