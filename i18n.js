// --- اللغة الحالية (Current Language) ---
let currentLang = localStorage.getItem('lang') || 'ar';

// --- دالة تغيير اللغة (Change Language Function) ---
function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('lang', lang);

    // تغيير اتجاه الصفحة
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;

    // تحديث جميع العناصر التي تحتوي على data-i18n
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[key] && translations[key][lang]) {
            element.textContent = translations[key][lang];
        }
    });

    // تحديث placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (translations[key] && translations[key][lang]) {
            element.placeholder = translations[key][lang];
        }
    });

    // تحديث زر اللغة
    const langBtn = document.querySelector('.lang-toggle');
    if (langBtn) {
        langBtn.innerHTML = translations['lang-button'][lang];
    }
}

// --- دالة تبديل اللغة (Toggle Language Function) ---
function toggleLanguage() {
    const newLang = currentLang === 'ar' ? 'en' : 'ar';
    changeLanguage(newLang);
}

// --- تهيئة اللغة عند تحميل الصفحة ---
document.addEventListener('DOMContentLoaded', () => {
    changeLanguage(currentLang);
});
